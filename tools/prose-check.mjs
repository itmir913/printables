// ── 본문 추출 ────────────────────────────────────────────────────────────────
// 검사하지 않는 부분은 지우되 줄바꿈은 유지해 원래 파일의 줄 번호를 보존한다.
const keepNewlines = (s) => s.replace(/[^\n]/g, '');
const BLOCK = new Set(['address', 'article', 'aside', 'blockquote', 'br', 'caption', 'cite', 'dd', 'div', 'dl', 'dt',
    'figcaption', 'figure', 'footer', 'h1', 'h2', 'h3', 'h4', 'h5', 'h6', 'header', 'hr', 'li', 'main', 'nav', 'ol', 'p',
    'section', 'table', 'tbody', 'td', 'tfoot', 'th', 'thead', 'tr', 'ul', 'body', 'head', 'html', 'title', 'img']);
const ENT = {amp: '&', lt: '<', gt: '>', quot: '"', apos: "'", nbsp: ' ', mdash: '—', ndash: '–', middot: '·',
    rarr: '→', larr: '←', hellip: '…', lsquo: '‘', rsquo: '’', ldquo: '“', rdquo: '”', times: '×'};
const decode = (s) => s.replace(/&(#x[0-9a-f]+|#\d+|[a-z]+);/gi, (m, e) =>
    e[0] === '#' ? String.fromCodePoint(e[1].toLowerCase() === 'x' ? parseInt(e.slice(2), 16) : +e.slice(1))
        : (ENT[e.toLowerCase()] ?? m));

export function htmlText(src) {
    let t = src.replace(/<(style|script|code|pre|kbd|samp)\b[^>]*>[\s\S]*?<\/\1\s*>/gi, (m) => ' ' + keepNewlines(m));
    t = t.replace(/<!--|-->/g, '  ');                 // 주석은 내용을 남긴다 — 발표자 메모다
    t = t.replace(/<!?\/?([a-zA-Z][\w-]*)?\b([^>]*)>/g, (m, name = '', attrs = '') => {
        const kept = [...attrs.matchAll(/\b(?:alt|title)\s*=\s*(?:"([^"]*)"|'([^']*)')/gi)].map((a) => a[1] ?? a[2]);
        const sep = BLOCK.has(name.toLowerCase()) || kept.length ? ' ' : '';
        return sep + kept.join(' ') + sep + keepNewlines(m);
    });
    return decode(t);
}

export function mdText(src) {
    let fence = null;
    return src.split('\n').map((line) => {
        const f = line.match(/^\s*(`{3,}|~{3,})/);
        if (fence) { if (f && f[1][0] === fence[0] && f[1].length >= fence.length) fence = null; return ''; }
        if (f) { fence = f[1]; return ''; }
        return line.replace(/(`+)[^`]*?\1/g, ' ');
    }).join('\n');
}

const jsText = (src) => src.split('\n').map((l) => (/^\s*\/\//.test(l) ? l : '')).join('\n');

function textOf(file, src) {
    const ext = path.extname(file).toLowerCase();
    if (ext === '.html' || ext === '.htm') return htmlText(src);
    if (ext === '.md') return mdText(src);
    if (ext === '.mjs' || ext === '.js') return jsText(src);
    return src;
}

// 인용 부호(「」 · "" · “”) 안에서 검출되었는가 — 구어 인용일 수 있으므로 표시만 한다.
function inQuote(line, i) {
    const pre = line.slice(0, i);
    const cnt = (ch) => pre.split(ch).length - 1;
    return cnt('「') > cnt('」') || cnt('“') > cnt('”') || cnt('"') % 2 === 1;
}

export function checkFile(file) {
    const src = fs.readFileSync(file, 'utf8').replace(/\r\n?/g, '\n');
    const raw = src.split('\n');
    const lines = textOf(file, src).split('\n');
    const out = [];
    lines.forEach((line, k) => {
        if (raw[k]?.includes(SKIP_LINE)) return;
        for (const [rx, 쓴, 쓸] of RULES) {
            rx.lastIndex = 0;
            for (const m of line.matchAll(rx)) {
                out.push({line: k + 1, 쓴, 쓸, quote: inQuote(line, m.index), text: line.replace(/\s+/g, ' ').trim()});
            }
        }
    });
    return out;
}

const SKIP_DIR = (name) => name.startsWith('.') || name === 'node_modules' || name === '_배부용' || name === 'dist';

function walk(dir) {
    const out = [];
    for (const e of fs.readdirSync(dir, {withFileTypes: true})) {
        const p = path.join(dir, e.name);
        if (e.isDirectory()) { if (!SKIP_DIR(e.name)) out.push(...walk(p)); }
        else if (/\.(html?|md)$/i.test(e.name) && e.name !== 'CLAUDE.md') out.push(p);
    }
    return out;
}

